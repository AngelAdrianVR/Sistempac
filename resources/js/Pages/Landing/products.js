/**
 * Genera un slug a partir de un string.
 * @param {string} text - El texto a convertir.
 * @returns {string} - El slug generado.
 */
const generateSlug = (text) => {
    return text
        .toLowerCase()
        .replace(/ /g, '-')
        .replace(/[^\w-]+/g, '');
};


